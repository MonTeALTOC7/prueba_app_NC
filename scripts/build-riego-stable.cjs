/* Materializes the existing R7.5.6 loader transformations at packaging time.
   Original and loader remain intact as audit sources. No agronomic change. */
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');const assets=path.join(root,'modules/riego/assets');
const original=fs.readFileSync(path.join(assets,'index-R75-ESTABLE-ORIGINAL.js'),'utf8');
let loader=fs.readFileSync(path.join(assets,'index-R75-ESTABLE.js'),'utf8');
loader=loader.replace("new URL('./index-R75-ESTABLE-ORIGINAL.js', import.meta.url)","'original-local'");
loader=loader.replace("new URL('./html2canvas.esm-BfxBtG_O.js', import.meta.url).href","'./html2canvas.esm-BfxBtG_O.js'");
const cut=loader.indexOf('  const blobUrl = URL.createObjectURL');if(cut<0)throw Error('Loader anchor not found');
loader=loader.slice(0,cut)+'return source;\n}\nglobalThis.result=boot();';
const warnings=[];
const context={fetch:async()=>({ok:true,text:async()=>original}),console:{warn:x=>warnings.push(x)},URL};
vm.createContext(context);vm.runInContext(loader,context);
context.result.then(source=>{
 const output=path.join(assets,'index-R756-UI110.js');
 const result='/* R7.5.6 materialized; generated by scripts/build-riego-stable.cjs. */\n'+source;
 if(process.argv.includes('--check')){if(fs.readFileSync(output,'utf8')!==result)throw Error('Generated Riego does not match its original loader');console.log('Riego: equivalent to existing loader; relative image-export dependency preserved.');}
 else{fs.writeFileSync(output,result);console.log('Riego materialized:',Buffer.byteLength(result),'bytes.');}
 console.log('Optional legacy-label warnings:',warnings.length);
}).catch(e=>{console.error(e.message);process.exitCode=1});
